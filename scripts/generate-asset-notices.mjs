import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const registryUrl = new URL('content/assets/registry.json', root);
const publicDirectory = new URL('public/', root);
const outputUrl = new URL('THIRD_PARTY_ASSETS.txt', publicDirectory);
const registry = JSON.parse(readFileSync(registryUrl, 'utf8'));

if (registry.schemaVersion !== 1) throw new Error('Unsupported asset registry schema version');
if (!Array.isArray(registry.sources) || !Array.isArray(registry.assets)) {
  throw new Error('Asset registry must contain sources[] and assets[]');
}

const sourceById = new Map();
for (const source of registry.sources) {
  if (!source?.id) throw new Error('Asset source is missing id');
  if (sourceById.has(source.id)) throw new Error(`Duplicate asset source id: ${source.id}`);
  sourceById.set(source.id, source);
}

const seenAssetIds = new Set();
const notices = [];
for (const asset of registry.assets) {
  if (!asset?.id) throw new Error('Bundled asset is missing id');
  if (seenAssetIds.has(asset.id)) throw new Error(`Duplicate bundled asset id: ${asset.id}`);
  seenAssetIds.add(asset.id);

  const source = sourceById.get(asset.sourceId);
  if (!source) throw new Error(`${asset.id}: unknown asset source ${asset.sourceId}`);
  if (source.status !== 'approved' && source.status !== 'candidate') {
    throw new Error(`${asset.id}: source ${source.id} is not approved/candidate for bundling`);
  }

  for (const field of registry.policy?.requiredForBundledAsset ?? []) {
    if (asset[field] === undefined || asset[field] === null || asset[field] === '') {
      throw new Error(`${asset.id}: required asset field ${field} is missing`);
    }
  }

  if (source.attributionRequired && !String(asset.attributionText ?? '').trim()) {
    throw new Error(`${asset.id}: ${source.id} requires attributionText`);
  }

  const lines = [
    `Asset: ${asset.id}`,
    `Source: ${source.repository ?? source.id}`,
    `Source item: ${asset.sourcePathOrName}`,
    `License: ${asset.license}`,
    `Modified: ${asset.modificationStatus}`
  ];
  if (asset.attributionText) lines.push(`Attribution: ${asset.attributionText}`);
  if (asset.licenseNotice) lines.push(`License notice: ${asset.licenseNotice}`);
  notices.push(lines.join('\n'));
}

mkdirSync(publicDirectory, { recursive: true });
const header = [
  'Kidsplay — Third-Party Artwork Notices',
  '========================================',
  '',
  'This file is generated from content/assets/registry.json.',
  'Do not edit this file directly.',
  ''
].join('\n');
const body = notices.length
  ? notices.join('\n\n----------------------------------------\n\n')
  : 'No third-party artwork is currently bundled.\n';
writeFileSync(outputUrl, `${header}${body}`, 'utf8');
console.log(`Generated asset notices for ${notices.length} bundled asset(s).`);
